import { afterAll, beforeAll, expect, it } from "vitest";
import { login, resetDb, setTestEnv } from "./helpers";
setTestEnv();
const { createApp } = await import("../server/app");
const { getDb, closeDb } = await import("../server/db");
const { contentItems, channels } = await import("../shared/schema");
const { eq } = await import("drizzle-orm");
let app: ReturnType<typeof createApp>;
beforeAll(async () => { await resetDb(); app = createApp(); });
afterAll(closeDb);
it("키워드·자료·브리핑·제작에서 같은 분류를 저장하고 버전 충돌을 막는다", async () => {
  const { agent, csrf } = await login(app), headers = { "x-csrf-token": csrf }, db = getDb();
  const [ch] = await db.select().from(channels).where(eq(channels.slug, "opportunities"));
  const rule = await agent.post(`/api/channels/${ch.id}/rules`).set(headers).send({ query: "테스트 입시", endpoints: ["news"], subcategory: "중등입시" });
  expect(rule.status).toBe(201);
  expect(rule.body.created[0].subcategory).toBe("중등입시");
  const queued = await agent.post("/api/collection/collect").set(headers).send({ channelId: ch.id, subcategory: "중등입시" });
  expect(queued.status).toBe(202);
  expect((await agent.post("/api/collection/collect").set(headers).send({ channelId: "all", subcategory: "중등입시" })).status).toBe(400);
  const { runCollect } = await import("../server/worker/collect");
  const { naverResponse } = await import("./helpers");
  const searched: string[] = [];
  const result = await runCollect(db, ch.id, { trigger: "manual", collectionOnly: true, subcategory: "중등입시", naverFetch: (async (url: string | URL | Request) => { searched.push(String(url)); return naverResponse([]); }) as typeof fetch });
  expect(result.counts.rulesProcessed).toBe(1);
  expect(result.counts.officialBoards).toBe(0);
  expect(searched).toHaveLength(1);
  const invalid = await agent.patch(`/api/channels/${ch.id}/rules/${rule.body.created[0].id}`).set(headers).send({ version: 1, subcategory: "정치" });
  expect(invalid.status).toBe(400);
  const [item] = await db.insert(contentItems).values({ channelId: ch.id, kind: "notice", title: "테스트 모집", category: "영재교육원", createdAt: new Date("2026-11-01T02:00:00Z") }).returning();
  const url = `/api/channels/${ch.id}/items/${item.id}/subcategory`;
  expect((await agent.patch(url).set(headers).send({ version: item.version, subcategory: "전국대회" })).status).toBe(200);
  expect((await agent.patch(url).set(headers).send({ version: item.version, subcategory: "고등입시" })).status).toBe(409);
  const list = await agent.get(`/api/items?channelId=${ch.id}&subcategory=${encodeURIComponent("전국대회")}&collectedOn=2026-11-01`);
  expect(list.body.items.map((r: any) => r.item.id)).toContain(item.id);
  expect(list.body.items.find((r: any) => r.item.id === item.id).item.category).toBe("영재교육원");
  const summary = await agent.get(`/api/collection/overview?channelId=${ch.id}&date=2026-11-01`);
  expect(summary.body.channels[0].categories.find((c: any) => c.label === "전국대회").newItems).toBe(1);
  const created = await agent.post("/api/studio/cards").set(headers).send({ title: "테스트 작업", channel: "highscoop", sourceItemId: item.id });
  expect(created.status).toBe(201); expect(created.body.subcategory).toBe("전국대회");
  const moved = await agent.patch(`/api/studio/cards/${created.body.id}`).set(headers).send({ version: created.body.version, stage: "writing" });
  expect(moved.body.subcategory).toBe("전국대회");
  expect((await agent.patch(`/api/studio/cards/${created.body.id}`).set(headers).send({ version: moved.body.version, subcategory: "과학" })).status).toBe(400);
});
